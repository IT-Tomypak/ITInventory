// lib/handover-pdf.js — the IT hardware handover form (A4) the recipient signs.
// Built in the browser with the same hand-written PDF writer as the request
// receipt, so no PDF library is needed.
import { esc, pdfFile, sanitize, width, wrap } from "./receipt-pdf.js";

const W = 595, H = 842; // A4 portrait, in points
const M = 48;
const LABEL_W = 150;    // label column of each table
// ponytail: pdfFile writes one page and 8 rows is what fits on it. Make pdfFile multi-page if one form must hold more.
export const MAX_HANDOVER_ITEMS = 8;

// "2026-09-23" -> "23/9/2026", the way the paper form writes it.
const dmy = (iso) => { const [y, m, d] = String(iso ?? "").split("-"); return d ? `${+d}/${+m}/${y}` : iso || ""; };

/**
 * d = { fullName, employeeNo, designation, department, purpose, dateReceived (YYYY-MM-DD),
 *       devices: [{ type, name }], issuedBy, company }
 * Returns the PDF as a Uint8Array.
 */
export function buildHandoverPdf(d) {
  const ops = [];
  const summary = d.devices.length === 1 ? d.devices[0].name : `${d.devices.length} items`;
  const text = (x, y, s, { size = 10, bold = false, gray = 0.11, align = "left" } = {}) => {
    const str = sanitize(s);
    const tx = align === "right" ? x - width(str, size, bold) : x;
    ops.push(`${gray} g BT /${bold ? "F2" : "F1"} ${size} Tf ${tx.toFixed(2)} ${y.toFixed(2)} Td (${esc(str)}) Tj ET`);
  };
  const fill = (x, y, w, h, rgb) => ops.push(`${rgb} rg ${x} ${y} ${w} ${h} re f`);
  const box = (x, y, w, h) => ops.push(`0.85 G 0.6 w ${x} ${y} ${w} ${h} re S`);
  const line = (x1, y1, x2, y2) => ops.push(`0.6 G 0.6 w ${x1} ${y1} m ${x2} ${y2} l S`);

  // Header bar
  fill(0, H - 70, W, 70, "0.114 0.114 0.122");
  text(M, H - 38, d.company || "", { size: 14, bold: true, gray: 1 });
  text(M, H - 54, "IT Department", { size: 9, gray: 0.75 });
  text(W - M, H - 38, "IT HARDWARE HANDOVER FORM", { size: 11, bold: true, gray: 1, align: "right" });
  text(W - M, H - 54, `Device: ${summary}`, { size: 9, gray: 0.75, align: "right" });

  let y = H - 110;
  // A titled two-column table; long values wrap and grow their row.
  const table = (title, rows, pad = 14) => {
    fill(M, y - 24, W - 2 * M, 24, "0.93 0.95 0.97");
    box(M, y - 24, W - 2 * M, 24);
    text(M + 10, y - 16, title, { size: 8.5, bold: true, gray: 0.35 });
    y -= 24;
    for (const [label, value] of rows) {
      const vs = wrap(value || "-", 10.5, W - 2 * M - LABEL_W - 20);
      const h = pad + vs.length * 13;
      const base = y - pad / 2 - 10;
      fill(M, y - h, LABEL_W, h, "0.97 0.98 0.99");
      box(M, y - h, LABEL_W, h);
      box(M + LABEL_W, y - h, W - 2 * M - LABEL_W, h);
      text(M + 10, base, label, { size: 10, gray: 0.4 });
      vs.forEach((v, i) => text(M + LABEL_W + 10, base - i * 13, v, { size: 10.5, bold: true }));
      y -= h;
    }
    y -= 22;
  };

  table("1. RECIPIENT DETAILS", [
    ["Full Name", d.fullName], ["Employee ID", d.employeeNo], ["Designation", d.designation],
    ["Department", d.department], ["Purpose", d.purpose], ["Date Received", dmy(d.dateReceived)],
  ]);
  table("2. ASSIGNED HARDWARE", [["Device Type", "Device Name / Host"], ...d.devices.map((x) => [x.type, x.name])], 5);

  // 3. Acknowledgement and signatures
  fill(M, y - 24, W - 2 * M, 24, "0.93 0.95 0.97");
  box(M, y - 24, W - 2 * M, 24);
  text(M + 10, y - 16, "3. ACKNOWLEDGEMENT", { size: 8.5, bold: true, gray: 0.35 });
  y -= 42;
  for (const l of wrap("I acknowledge that I have received the hardware listed above in good working condition. "
    + "I will use it for company purposes only, take reasonable care of it, and return it to the IT Department "
    + "on request or when I leave the company.", 10, W - 2 * M - 20)) {
    text(M + 10, y, l, { size: 10, gray: 0.2 });
    y -= 14;
  }

  y -= 20;
  const colW = (W - 2 * M - 24) / 2;
  [["Received by (Recipient)", d.fullName], ["Issued by (IT Department)", d.issuedBy]].forEach(([title, name], i) => {
    const x = M + i * (colW + 24);
    box(x, y - 150, colW, 150);
    text(x + 12, y - 20, title, { size: 9, bold: true, gray: 0.35 });
    line(x + 12, y - 80, x + colW - 12, y - 80);
    text(x + 12, y - 94, "Signature", { size: 8, gray: 0.5 });
    text(x + 12, y - 116, `Name: ${name || ""}`, { size: 9.5, gray: 0.15 });
    text(x + 12, y - 136, "Date:", { size: 9.5, gray: 0.15 });
    line(x + 42, y - 138, x + colW - 12, y - 138);
  });

  text(M, 36, `Generated by ITrack - ${d.company || ""}`, { size: 8, gray: 0.5 });
  return pdfFile(ops, W, H, `Handover ${summary} - ${d.fullName || ""}`);
}

/** Save PDF bytes as a download in the browser. */
export function downloadPdf(bytes, filename) {
  const a = Object.assign(document.createElement("a"), {
    href: URL.createObjectURL(new Blob([bytes], { type: "application/pdf" })),
    download: filename,
  });
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(a.href), 1000);
}
